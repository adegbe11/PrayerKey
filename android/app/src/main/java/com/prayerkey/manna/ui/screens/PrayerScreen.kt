private val PrayViolet = Pk.Oxblood
private val PrayInk = Pk.Charcoal
private val PrayMuted = Pk.Muted

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PrayerScreen(
    journal: List<JournalPrayer>,
    topics: List<PrayerTopic>,
    topicsReady: Boolean,
    onLoadTopics: () -> Unit,
    onSavePrayer: (String, GeneratedPrayer) -> Unit,
    initialRequest: String? = null,
    onInitialRequestConsumed: () -> Unit = {},
) {
    var request by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<GeneratedPrayer?>(null) }
    var loading by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var deckOpen by remember { mutableStateOf(false) }
    var category by remember { mutableStateOf<String?>(null) }
    var selectedTopic by remember { mutableStateOf<PrayerTopic?>(null) }
    val scope = rememberCoroutineScope()
    val context = LocalContext.current
    var speechReady by remember { mutableStateOf(false) }
    val speaker = remember { TextToSpeech(context.applicationContext) { speechReady = it == TextToSpeech.SUCCESS } }
    LaunchedEffect(speechReady) { if (speechReady) { speaker.language = Locale.getDefault(); speaker.setSpeechRate(.86f) } }
    DisposableEffect(speaker) { onDispose { speaker.stop(); speaker.shutdown() } }
    LaunchedEffect(Unit) { onLoadTopics() }
    LaunchedEffect(initialRequest) {
        if (!initialRequest.isNullOrBlank()) {
            request = initialRequest
            generated = null
            onInitialRequestConsumed()
        }
    }

    if (deckOpen) {
        if (category == null) {
            PrayerSituationLibrary(topics, topics.isEmpty() && !topicsReady, onLoadTopics, { deckOpen = false }) { category = it }
        } else {
            val cards = remember(topics, category) { topics.filter { it.category.equals(category, true) } }
            Box(Modifier.fillMaxSize().background(PrayBlack)) {
                if (cards.isEmpty()) {
                    Column(Modifier.fillMaxSize(), verticalArrangement = Arrangement.Center, horizontalAlignment = Alignment.CenterHorizontally) {
                        CircularProgressIndicator(color = PrayViolet)
                        Text("Preparing this prayer deck…", Modifier.padding(top = 16.dp), color = PrayMuted)
                    }
                } else {
                    com.prayerkey.manna.ui.components.PullDeck(
                        items = cards, pullStamp = "NEXT", keepStamp = "KEPT",
                        onKeep = { topic -> onSavePrayer(topic.title, GeneratedPrayer(topic.slug, topic.title, topic.prayer, "", topic.scripture)) },
                        topOverlay = { index -> PrayerDeckCategoryHeader(category.orEmpty(), index + 1, cards.size) { category = null } },
                    ) { topic, front, modifier -> PrayerDeckFace(topic, front, { selectedTopic = topic }, modifier) }
                }
            }
        }
        return
    }

    Surface(Modifier.fillMaxSize(), color = PrayBlack) {
        Column(Modifier.fillMaxSize().statusBarsPadding()) {
            Row(Modifier.fillMaxWidth().padding(horizontal = 20.dp, vertical = 14.dp), verticalAlignment = Alignment.CenterVertically) {
                Text("PRAYERKEY", Modifier.weight(1f), color = PrayInk, fontFamily = UtilitySans, fontSize = 25.sp, fontWeight = FontWeight.Bold)
                RoundAction(Icons.Outlined.AutoStories, "Prayer decks") { deckOpen = true }
                Spacer(Modifier.width(9.dp))
            }
            Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(horizontal = 20.dp).padding(bottom = 120.dp)) {
                if (generated == null) {
                    Text("What's on your heart?", Modifier.padding(top = 31.dp), color = PrayInk, fontFamily = DisplaySerif, fontWeight = FontWeight.Bold, fontSize = 32.sp, lineHeight = 38.sp)
                    Text(
                        "Share what you’re facing, carrying, or hoping for. PrayerKey will help you turn it into a personal, Bible-grounded prayer.",
                        Modifier.padding(top = 12.dp, bottom = 26.dp), color = PrayMuted, fontFamily = UtilitySans, fontStyle = FontStyle.Italic, fontSize = 16.sp, lineHeight = 24.sp,
                    )
                    PrayerComposer(request, loading, { request = it }) {
                        if (request.isNotBlank() && !loading) scope.launch {
                            loading = true; error = null
                            runCatching { PrayerKeyApi.generatePrayerReliable(request, emptyList()) }
                                .onSuccess { generated = it }
                                .onFailure { error = it.message ?: "Prayer could not be prepared. Please try again." }
                            loading = false
                        }
                    }
                    Text(
                        "You can begin with one honest sentence. Your words stay private unless you choose to keep the prayer.",
                        Modifier.padding(top = 20.dp),
                        color = PrayMuted,
                        fontFamily = UtilitySans,
                        fontSize = 13.sp,
                        lineHeight = 20.sp,
                    )
                    Text(
                        "BEGIN WITH",
                        Modifier.padding(top = 28.dp, bottom = 10.dp),
                        color = PrayMuted, fontFamily = UtilitySans,
                        fontSize = 10.sp, letterSpacing = 1.4.sp, fontWeight = FontWeight.Bold,
                    )
                    Row(
                        Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()),
                        horizontalArrangement = Arrangement.spacedBy(9.dp),
                    ) {
                        listOf("My family", "Healing", "A decision", "Peace today").forEach { prompt ->
                            Surface(
                                onClick = { request = "Please help me pray for ${prompt.lowercase()}." },
                                shape = RoundedCornerShape(99.dp), color = PrayPanel,
                                border = BorderStroke(1.dp, PrayLine),
                            ) {
                                Text(
                                    prompt, Modifier.padding(horizontal = 14.dp, vertical = 10.dp),
                                    color = PrayInk, fontSize = 12.sp, fontWeight = FontWeight.Medium,
                                )
                            }
                        }
                    }
                    error?.let { Text(it, Modifier.padding(top = 12.dp), color = Color(0xFFFF9B9B), fontSize = 12.sp) }
                    if (journal.isNotEmpty()) {
                        Text("PRAYERS YOU KEPT", Modifier.padding(top = 31.dp, bottom = 10.dp), color = PrayMuted, fontSize = 10.sp, letterSpacing = 1.5.sp, fontWeight = FontWeight.Bold)
                        journal.take(3).forEach { saved ->
                            Surface(onClick = { request = saved.request }, modifier = Modifier.fillMaxWidth().padding(bottom = 9.dp), shape = RoundedCornerShape(22.dp), color = PrayPanel, border = BorderStroke(1.dp, PrayLine), shadowElevation = 2.dp) {
                                Row(Modifier.padding(16.dp), verticalAlignment = Alignment.CenterVertically) {
                                    Icon(Icons.Outlined.BookmarkBorder, null, tint = PrayGold)
                                    Column(Modifier.weight(1f).padding(start = 13.dp)) { Text(saved.title, color = PrayInk, fontFamily = BookSerif, fontSize = 17.sp); saved.scriptureRef?.let { Text(it, color = PrayMuted, fontSize = 11.sp) } }
                                    Icon(Icons.Outlined.ChevronRight, null, tint = PrayMuted)
                                }
                            }
                        }
                    }
                } else {
                    GeneratedPrayerView(generated!!, speechReady, onListen = { speaker.speak("${generated!!.title}. ${generated!!.prayer}", TextToSpeech.QUEUE_FLUSH, null, generated!!.id) }, onSave = { onSavePrayer(request, generated!!) }, onAgain = { generated = null; request = "" })
                }
            }
        }
    }

    selectedTopic?.let { topic ->
        ModalBottomSheet(onDismissRequest = { selectedTopic = null }, containerColor = Pk.Cream) {
            Column(Modifier.fillMaxWidth().padding(horizontal = 24.dp, vertical = 12.dp).padding(bottom = 36.dp)) {
                Text(topic.title, fontFamily = DisplaySerif, fontWeight = FontWeight.Bold, fontSize = 28.sp, color = Pk.Charcoal)
                Text(topic.prayer, Modifier.padding(top = 18.dp), fontFamily = BookSerif, fontSize = 18.sp, lineHeight = 28.sp, color = Pk.Charcoal)
            }
        }
    }
}

@Composable private fun RoundAction(icon: androidx.compose.ui.graphics.vector.ImageVector, description: String, action: () -> Unit) = Surface(onClick = action, shape = CircleShape, color = PrayPanel, border = BorderStroke(1.dp, PrayLine)) {
    Icon(icon, description, Modifier.padding(11.dp).size(21.dp), tint = PrayInk)
}

@Composable private fun PrayerComposer(value: String, loading: Boolean, onChange: (String) -> Unit, onSend: () -> Unit) {
    Surface(Modifier.fillMaxWidth(), shape = RoundedCornerShape(28.dp), color = PrayPanel, border = BorderStroke(1.dp, PrayLine), shadowElevation = 4.dp) {
        Column(Modifier.padding(18.dp)) {
            androidx.compose.foundation.text.BasicTextField(value, onChange, Modifier.fillMaxWidth().heightIn(min = 88.dp), textStyle = androidx.compose.ui.text.TextStyle(color = PrayInk, fontFamily = UtilitySans, fontSize = 18.sp, lineHeight = 27.sp), decorationBox = { inner -> Box { if (value.isBlank()) Text("Tell God what is on your heart…", color = PrayMuted, fontSize = 18.sp); inner() } })
            Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                Icon(Icons.Outlined.MicNone, "Voice prayer", tint = PrayMuted)
                Spacer(Modifier.weight(1f))
                Surface(onClick = onSend, enabled = value.isNotBlank() && !loading, shape = CircleShape, color = if (value.isNotBlank()) PrayViolet else Color(0xFFE8E3ED)) {
                    if (loading) CircularProgressIndicator(Modifier.padding(12.dp).size(21.dp), color = Color.White, strokeWidth = 2.dp) else Icon(Icons.Outlined.ArrowUpward, "Pray with me", Modifier.padding(12.dp), tint = Color.White)
                }
            }
        }
    }
}

@Composable private fun GeneratedPrayerView(prayer: GeneratedPrayer, speechReady: Boolean, onListen: () -> Unit, onSave: () -> Unit, onAgain: () -> Unit) {
    Text("A prayer for you", Modifier.padding(top = 34.dp), color = PrayGold, fontSize = 11.sp, fontWeight = FontWeight.Bold, letterSpacing = 1.5.sp)
    Text(prayer.title, Modifier.padding(top = 10.dp), color = PrayInk, fontFamily = DisplaySerif, fontWeight = FontWeight.Bold, fontSize = 34.sp, lineHeight = 39.sp)
    prayer.verses.firstOrNull()?.let { (ref, verse) -> Surface(Modifier.fillMaxWidth().padding(top = 24.dp), shape = RoundedCornerShape(24.dp), color = PrayPanel, border = BorderStroke(1.dp, PrayLine), shadowElevation = 2.dp) { Column(Modifier.padding(20.dp)) { Text(ref.uppercase(), color = PrayGold, fontSize = 10.sp, fontWeight = FontWeight.Bold, letterSpacing = 1.1.sp); Text("“$verse”", Modifier.padding(top = 8.dp), color = PrayInk, fontFamily = BookSerif, fontStyle = FontStyle.Italic, fontSize = 18.sp, lineHeight = 27.sp) } } }
    Text(prayer.prayer, Modifier.padding(top = 25.dp), color = PrayInk.copy(.9f), fontFamily = BookSerif, fontSize = 20.sp, lineHeight = 31.sp)
    if (prayer.encouragement.isNotBlank()) Text(prayer.encouragement, Modifier.padding(top = 20.dp), color = PrayMuted, fontSize = 14.sp, lineHeight = 22.sp)
    Row(Modifier.fillMaxWidth().padding(top = 28.dp), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
        OutlinedButton(onListen, enabled = speechReady, modifier = Modifier.weight(1f), border = BorderStroke(1.dp, PrayLine)) { Icon(Icons.Outlined.VolumeUp, null); Text(" LISTEN") }
        Button(onSave, modifier = Modifier.weight(1f), colors = ButtonDefaults.buttonColors(containerColor = PrayViolet)) { Icon(Icons.Outlined.BookmarkBorder, null); Text(" KEEP") }
    }
    TextButton(onAgain, Modifier.fillMaxWidth().padding(top = 12.dp)) { Text("PRAY ABOUT SOMETHING ELSE", color = PrayGold, fontSize = 11.sp, letterSpacing = .8.sp) }
}
